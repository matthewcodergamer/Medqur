Uint8List? _normalizedPrescriptionTemplate;

Uint8List prescriptionTemplatePngBytes() {
  final cached = _normalizedPrescriptionTemplate;
  if (cached != null) return cached;

  final compact = base64Decode(kPrescriptionTemplatePngBase64);
  final decoded = img.decodePng(compact);
  if (decoded == null) {
    return Uint8List.fromList(compact);
  }

  final normalized = img.Image(
    width: decoded.width,
    height: decoded.height,
    numChannels: 4,
  );
  for (var y = 0; y < decoded.height; y++) {
    for (var x = 0; x < decoded.width; x++) {
      final pixel = decoded.getPixel(x, y);
      normalized.setPixelRgba(
        x,
        y,
        pixel.r,
        pixel.g,
        pixel.b,
        255,
      );
    }
  }

  final bytes = Uint8List.fromList(img.encodePng(normalized, level: 6));
  _normalizedPrescriptionTemplate = bytes;
  return bytes;
}
